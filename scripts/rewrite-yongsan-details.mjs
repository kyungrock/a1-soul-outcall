function buildUniqueMids(count) {
  const seen = new Set();
  const out = [];
  const n = BANK.length;
  for (let i = 0; i < count; i++) {
    let t = 0;
    let s = "";
    for (;;) {
      const x = (i * 5 + t * 7 + 3) % n;
      const y = (i * 11 + t * 13 + 17) % n;
      const z = (i * 19 + t * 23 + 29) % n;
      if (x !== y && y !== z && z !== x) {
        s = `${BANK[x]} ${BANK[y]} ${BANK[z]}`.replace(/\s+/g, " ").trim();
        if (!seen.has(s)) break;
      }
      t++;
      if (t > 50000) throw new Error("unique mid generation failed at " + i);
    }
    seen.add(s);
    out.push(s);
  }
  return out;
}

